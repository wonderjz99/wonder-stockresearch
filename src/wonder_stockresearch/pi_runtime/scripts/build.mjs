// Publish generated JS beside package.json so installed Python wheels need no compiler.
import { readFile, writeFile } from 'node:fs/promises';

const runtime = new URL('../', import.meta.url);
const output = '// Generated from src/runner.ts. Run npm run build; do not edit this file.\n' +
  await readFile(new URL('build/runner.js', runtime), 'utf8');
const target = new URL('runner.mjs', runtime);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) {
    throw new Error('runner.mjs is stale; run npm run build');
  }
} else {
  await writeFile(target, output, 'utf8');
}
